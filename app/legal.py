@dataclass(frozen=True)
class Operator:
    name: str
    address: str
    phone: str

    @classmethod
    def of(cls, tenant: Tenant) -> "Operator":
        if tenant.slug == "demo":
            return cls(
                name="Штыков Егор Дмитриевич, самозанятый (плательщик НПД), "
                     "ИНН 772594573137, email: negay2020@gmail.com",
                address="",
                phone="",
            )
        return cls(
            name=tenant.display_name,
            address=", ".join(p for p in (tenant.city, tenant.address) if p),
            phone=tenant.phone,
        )

    def describe(self) -> str:
        parts = [self.name]
        if self.address:
            parts.append(f"адрес: {self.address}")
        if self.phone:
            parts.append(f"телефон: {self.phone}")
        return "; ".join(parts)


