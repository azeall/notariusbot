"""Тексты о персональных данных: согласие клиента и политика обработки.

Здесь один источник правды на все каналы. Раньше `CONSENT_VERSION` был объявлен
дважды — в виджете и в разговоре мессенджеров, — и правка одного места молча
расходилась со вторым. Цена такой рассогласованности не косметическая: в базе
хранится версия текста, и по ней потом доказывают, на что именно человек
согласился. Разные версии за одно и то же согласие делают доказательство
невозможным.

**Кто здесь оператор.** Оператор персональных данных — нотариус: это он решает,
зачем собираются данные, и это к нему человек пришёл. Сервис обрабатывает данные
по поручению оператора (ч. 3 ст. 6 152-ФЗ) и своих целей в них не имеет.
Поэтому в согласии называется контора нотариуса, а сервис упоминается как
обработчик. Написать наоборот — значит объявить себя оператором со всеми его
обязанностями, включая уведомление Роскомнадзора за каждого нотариуса.

**Почему текст хранится целиком, а не только номер версии.** Согласие
подтверждают один раз, а спрашивают о нём через годы. Номер версии без текста
доказывает только то, что номер был. Старые версии из словаря не удаляются
никогда — на них ссылаются записи в базе.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.models import Tenant

# Текущая версия. Меняется вместе с текстом — и только вместе с ним.
#
# Версии разные намеренно: 2026-09-05 — политика дополнена порядком действий
# при утечке и указанием, где лежат данные. Текст согласия при этом не менялся,
# и поднимать его версию нельзя: по ней в базе опознают, на что именно человек
# согласился, а он согласился на прежний текст.
CONSENT_VERSION = "2026-08-26"
POLICY_VERSION = "2026-09-05"


@dataclass(frozen=True)
class Operator:
    """Оператор глазами клиента: кому он доверяет данные.

    Собирается из карточки нотариуса. Пустые поля не подставляются заглушками:
    лучше короткий честный текст, чем «г. ____» в документе, который человек
    читает перед тем, как прислать паспорт.
    """

    name: str
    address: str
    phone: str

    @classmethod
    def of(cls, tenant: Tenant) -> "Operator":
        return cls(
            name=tenant.display_name,
            address=", ".join(p for p in (tenant.city, tenant.address) if p),
            phone=tenant.phone,
        )

    def describe(self) -> str:
        parts = [self.name]
        if self.address:
            parts.append(f"адрес: {self.address}")
        if self.phone:
            parts.append(f"телефон: {self.phone}")
        return "; ".join(parts)


# Что именно собирается. Перечень обязан совпадать с тем, что сервис на самом
# деле хранит, — иначе согласие получено не на то. Сверяется тестом с моделями.
PERSONAL_DATA_COLLECTED = (
    "фамилия и имя",
    "номер телефона",
    "выбранная нотариальная услуга и пожелания к визиту",
    "документы, которые вы пришлёте: их изображения или файлы, включая паспортные данные",
)

PROCESSING_PURPOSES = (
    "подготовить нотариальное действие: определить перечень необходимых документов",
    "связаться с вами и согласовать время приёма",
    "принять и передать нотариусу документы до визита",
)

# Порядок действий при утечке. Появился в 152-ФЗ статьёй 21.1 (внесена
# Федеральным законом от 30.11.2024 № 420-ФЗ, действует с 30.05.2025): оператор
# обязан уведомить Роскомнадзор в течение 24 часов о самом происшествии
# и в течение 72 часов — о результатах внутреннего расследования.
#
# Обязанность лежит на операторе, то есть на нотариусе. Но узнаёт об утечке
# первым сервис — данные лежат на его сервере, — поэтому в политике прямо
# написано, что сервис извещает нотариуса немедленно. Без этой строки нотариус
# узнавал бы о происшествии позже отведённых ему суток и нарушал бы срок
# не по своей вине.
INCIDENT_PROCEDURE = (
    "сервис извещает нотариуса немедленно, как только происшествие обнаружено, "
    "и передаёт всё, что известно: какие данные затронуты, когда и в каком объёме",
    "нотариус как оператор уведомляет Роскомнадзор в течение 24 часов "
    "с момента обнаружения — о самом происшествии",
    "в течение 72 часов нотариус сообщает Роскомнадзору результаты внутреннего "
    "расследования и сведения о виновных лицах",
    "если происшествие затронуло ваши данные, нотариус сообщает об этом вам "
    "по оставленным контактам",
)

# Где физически лежат данные. Вопрос не праздный: трансграничная передача
# (ст. 12 152-ФЗ) требует отдельного согласия и уведомления Роскомнадзора,
# и первое, что спрашивает проверяющий, — где сервер.
DATA_LOCATION = (
    "Данные обрабатываются и хранятся на сервере в Российской Федерации. "
    "За пределы России они не передаются: трансграничной передачи нет, и "
    "отдельного согласия на неё не требуется."
)

PROCESSING_ACTIONS = (
    "сбор",
    "запись",
    "хранение",
    "уточнение",
    "использование",
    "передача нотариусу",
    "удаление",
    "уничтожение",
)


def consent_text(tenant: Tenant, version: str = CONSENT_VERSION) -> str:
    """Полный текст согласия, который видит клиент.

    Версия передаётся явно, чтобы можно было показать старое согласие таким,
    каким его показывали тогда, — например, при разборе жалобы.
    """
    if version != CONSENT_VERSION:
        archived = _ARCHIVE.get(version)
        if archived is None:
            raise KeyError(f"Неизвестная версия согласия: {version}")
        return archived(tenant)
    return _consent_2026_08_26(tenant)


def _consent_2026_08_26(tenant: Tenant) -> str:
    operator = Operator.of(tenant)
    data = "\n".join(f"— {item}" for item in PERSONAL_DATA_COLLECTED)
    purposes = "\n".join(f"— {item}" for item in PROCESSING_PURPOSES)
    actions = ", ".join(PROCESSING_ACTIONS)
    return (
        "Согласие на обработку персональных данных\n\n"
        f"Я даю согласие на обработку моих персональных данных оператору: "
        f"{operator.describe()}.\n\n"
        "Цели обработки:\n"
        f"{purposes}\n\n"
        "Перечень персональных данных:\n"
        f"{data}\n\n"
        f"Действия с данными: {actions}.\n\n"
        "Обработку по поручению оператора выполняет сервис приёма заявок: он "
        "принимает и хранит данные по указанию нотариуса, своих целей в них не "
        "имеет и третьим лицам не передаёт. Данные хранятся на серверах "
        "в Российской Федерации.\n\n"
        "Срок действия согласия: до достижения целей обработки или до его отзыва. "
        "Присланные документы удаляются автоматически по истечении срока хранения, "
        "даже если согласие не отозвано.\n\n"
        "Согласие можно отозвать в любой момент — обратившись к нотариусу по "
        "указанным выше контактам. Отзыв согласия не отменяет нотариального "
        "действия, которое уже совершено."
    )


# Архив прежних версий. Пополняется, но не чистится: записи в базе ссылаются
# на эти ключи, и удалить текст — значит потерять доказательство.
_ARCHIVE: dict[str, object] = {}


def consent_summary() -> str:
    """Короткая строка для мессенджера, где длинный текст читать не станут.

    Полный текст не заменяется этой строкой, а дополняется ссылкой на него:
    согласие «не глядя» — это отсутствие согласия, а не его упрощённая форма.
    """
    return (
        "Для оформления заявки нужно ваше согласие на обработку персональных данных.\n\n"
        "Коротко: данные нужны, чтобы подготовить нотариальное действие и связаться "
        "с вами; оператор — нотариус; документы хранятся ограниченное время "
        "и удаляются автоматически; согласие можно отозвать."
    )
